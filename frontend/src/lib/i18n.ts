export type Lang = 'de' | 'en' | 'zh'

/**
 * Every language the UI can be shown in, in the order the pickers list them.
 * English is first because it is the default: a fresh install has to resolve to
 * a dictionary even when the stored settings carry no usable language.
 */
export const LANGS: { id: Lang; label: string }[] = [
  { id: 'en', label: 'English' },
  { id: 'de', label: 'Deutsch' },
  { id: 'zh', label: '中文' },
]

/**
 * The language a stored settings blob names, or English when it names something
 * this build does not ship. Kept here rather than in the backend so the
 * fallback lives next to the dictionaries it has to match.
 */
export function asLang(value: unknown): Lang {
  return value === 'de' || value === 'zh' ? value : 'en'
}


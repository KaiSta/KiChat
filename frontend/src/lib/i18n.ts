const dictionaries: Record<Lang, Record<string, string>> = { de, en }

/** Translate a key, falling back to the key itself so gaps are visible. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[lang] ?? de
  let text = dict[key] ?? de[key as keyof typeof de] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{{${name}}}`, String(value))
    }
  }
  return text
}
